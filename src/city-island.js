function beachPalmRows(props){
  const candidates=[
    ...Array.from({length:24},(_,i)=>[9088+(i%3)*4,5485+i*131]),
    ...Array.from({length:24},(_,i)=>[11290-(i%3)*4,5515+i*128]),
    ...Array.from({length:10},(_,i)=>[9500+i*155,5270+(i%2)*6]),
    ...Array.from({length:10},(_,i)=>[9450+i*155,8530+(i%3)*5]),
    [8675,6745],[8667,6860],[8679,6960],[8680,7055]
  ];
  const palms=[];
  for(const [index,[anchorX,y]] of candidates.entries()){
    const x=anchorX+harborEastShift;
    if(!isCityBeach(x,y,15)||props.some(prop=>Math.hypot(prop.x-x,prop.y-y)<23)||
      palms.some(palm=>Math.hypot(palm.x-x,palm.y-y)<55))continue;
    palms.push({x,y,angle:index*2.39996,height:24+(index*7)%16});
  }
  return palms;
}

export function harborBeachLayout(){
  const props=beachGroups();
  const palms=beachPalmRows(props);
  const palmTotal=palms.length*4,propTotal=props.length*4;
  let seed=73219;
  const random=()=>((seed=(Math.imul(seed,1664525)+1013904223)>>>0)/4294967296);
  const position=()=>({x:8630+harborEastShift+2748*random(),y:5180+3460*random()});
  const clear=(items,x,y,gap)=>items.every(item=>(item.x-x)**2+(item.y-y)**2>=gap**2);

  for(let attempt=0;palms.length<palmTotal&&attempt<30000;attempt++){
    const {x,y}=position();
    if(!isCityBeach(x,y,12)||!clear(palms,x,y,25)||!clear(props,x,y,19))continue;
    palms.push({x,y,angle:random()*Math.PI*2,height:22+random()*15});
  }

  for(let attempt=0;props.length<propTotal&&attempt<50000;attempt++){
    const {x,y}=position();
    const angle=random()*Math.PI*2;
    const setup=[
      ['Beach umbrella',x,y],
      ['Beach chair',x+Math.cos(angle)*15,y+Math.sin(angle)*15],
      [BEACH_KIT_NODES[2+attempt%4],x+Math.cos(angle+.9)*18,y+Math.sin(angle+.9)*18]
    ];
    for(const [name,px,py] of setup){
      if(!isCityBeach(px,py,10)||!clear(palms,px,py,17)||!clear(props,px,py,12))continue;
      props.push({name,x:px,y:py,angle});
      if(props.length===propTotal)break;
    }
  }
  return {props,palms};
}

