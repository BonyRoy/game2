function isCityBeach(x,y,margin=0){
  if(!insideCoast(dryBeachRows,x,y))return false;
  if(margin&&(!isCityLand(x-margin,y)||!isCityLand(x+margin,y)||
    !isCityLand(x,y-margin)||!isCityLand(x,y+margin)))return false;
  if(CITY_DISTRICTS.some(district=>Math.abs(x-district.x)<CITY_HALF_SIZE+margin&&Math.abs(y-district.y)<CITY_HALF_SIZE+margin)){
    return false;
  }
  const nearStreet=CITY_STREETS.some(([[ax,ay],[bx,by]])=>{
    const dx=x-Math.max(Math.min(ax,bx),Math.min(x,Math.max(ax,bx)));
    const dy=y-Math.max(Math.min(ay,by),Math.min(y,Math.max(ay,by)));
    return dx*dx+dy*dy<(48+margin)**2;
  });
  const pier=x>=CITY.x-945-margin&&x<=CITY.x-CITY_HALF_SIZE+margin&&Math.abs(y-CITY.y)<=215+margin;
  const bridgeApproach=x<CITY.x&&Math.abs(y-CITY_BRIDGE.y)<=CITY_BRIDGE.width/2+margin;
  return !nearStreet&&!pier&&!bridgeApproach;
}

